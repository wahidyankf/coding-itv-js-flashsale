// Renders the behaviour status report that `npm run bdd:check` writes to generated-reports/. It only formats what the
// checker found: each scenario's bindings per layer, the coverage, and the failures.

// One layer's column. An exemption shows as exempt; otherwise the layer is bound or missing.
function layerStatus(exempt, bound) {
	if (exempt) return "exempt";
	return bound ? "bound" : "missing";
}

// The report as Markdown: a header, one row per scenario, and the failures when there are any.
export function renderReport(scenarios, failures, covered, total) {
	const pct = total === 0 ? 100 : Math.round((covered / total) * 100);
	const lines = [
		"# Behaviour status",
		"",
		"Generated by `npm run bdd:check`. Do not edit; run the check again instead.",
		"",
		`Behaviour coverage: ${covered}/${total} (${pct}%)`,
		"",
		"| Owner | Feature | Scenario | Rows | Unit | Integration | E2E |",
		"| --- | --- | --- | --- | --- | --- | --- |",
	];
	for (const scenario of scenarios) {
		const unit = scenario.bound.unit ? "bound" : "missing";
		const integration = layerStatus(
			scenario.exempt.integration,
			scenario.bound.integration,
		);
		const e2e = layerStatus(scenario.exempt.e2e, scenario.bound.e2e);
		lines.push(
			`| ${scenario.owner} | ${scenario.file} | ${scenario.name} | ${scenario.rows.length} | ${unit} | ${integration} | ${e2e} |`,
		);
	}
	if (failures.length > 0) {
		lines.push("", "## Failures", "");
		for (const failure of failures) lines.push(`- ${failure}`);
	}
	return `${lines.join("\n")}\n`;
}
