// Unit tests of flash-web: plain *_tests.ts(x) beside the source, in jsdom. `test:unit` runs them, and the 99% gate in
// vitest.coverage.config.ts counts them together with the integration tests.
import viteReact from "@vitejs/plugin-react";
import { defineConfig } from "vitest/config";

export default defineConfig({
	plugins: [viteReact()],
	test: {
		name: "unit",
		environment: "jsdom",
		// The integration files need the dev stack, so they run only in their own config.
		include: ["src/**/*_tests.{ts,tsx}"],
		exclude: ["node_modules", ".output", "src/**/*_integration_tests.{ts,tsx}"],
		// Report only. Unit tests alone do not reach 99%; the 99% gate is on the combined run.
		coverage: {
			provider: "v8",
			include: ["src/**/*.{ts,tsx}"],
			exclude: [
				// Test code is not product code.
				"src/**/*_tests.{ts,tsx}",
				"src/**/*_integration_tests.{ts,tsx}",
				"src/bdd/**",
				// Generated by TanStack Router from the route files. Its output is not authored code.
				"src/routeTree.gen.ts",
			],
			reporter: ["text", "text-summary"],
		},
	},
});
